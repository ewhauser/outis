"""Write results/COMPARISON.md: one table per benchmark, current aligned view first.

Run with the project virtual environment after ``score.py`` and
``score_aligned.py``. It only reads result files. For each benchmark with a
current aligned-view result, it lists every system there with the aligned
headline metrics, the as-published character recall and non-PII redaction
beside them when ``score.py`` has scored that system, and the convention-gap
flags from ``score_aligned.convention_flags``.

  python compare.py
"""
from __future__ import annotations

import json

from common import RESULTS
from score_aligned import VIEW, convention_flags


def pct(value) -> str:
    return "–" if value is None else f"{100 * value:.2f}%"


def published(benchmark: str, system: str) -> dict | None:
    path = RESULTS / f"{benchmark}.{system}.json"
    return json.loads(path.read_text())["label_agnostic"] if path.exists() else None


def main() -> None:
    lines = [
        "# External comparison",
        "",
        f"Generated by `compare.py` from the `{VIEW}` results. Read the aligned columns "
        "first: they score every system under this project's policy, with convention "
        "and requirement differences neutralised (`score_aligned.py`). The as-published "
        "columns use each benchmark's own gold, which penalises conventions the policy "
        "deliberately differs on (honorifics and credentials inside names, unannotated "
        "ages and years). Before attributing a gap to a model, check the convention "
        f"flags and the miss shapes in `<benchmark>.{VIEW}.json`.",
        "",
    ]
    for path in sorted(RESULTS.glob(f"*.{VIEW}.json")):
        benchmark = path.name[: -len(f".{VIEW}.json")]
        results = json.loads(path.read_text())
        lines += [
            f"## {benchmark}",
            "",
            "| System | Value-char recall | Non-PHI redaction | Direct | NAME (doc 95% lb) | Indirect "
            "| Leak-free PHI docs | Char recall (published) | Non-PII redaction (published) |",
            "|---|---:|---:|---:|---:|---:|---:|---:|---:|",
        ]
        for r in sorted(results, key=lambda r: -r["value_character_recall"]):
            raw = published(benchmark, r["system"])
            lines.append(
                f"| {r['system']} | {pct(r['value_character_recall'])} | {pct(r['non_phi_redaction'])} "
                f"| {pct(r['direct']['recall'])} | {pct(r['name']['recall'])} "
                f"({pct(r['name']['recall_cluster_lower_95'])}) | {pct(r['indirect']['recall'])} "
                f"| {pct(r['phi_documents_leak_free']['rate'])} "
                f"| {pct(raw['character_recall']) if raw else '–'} "
                f"| {pct(raw['non_pii_redaction']) if raw else '–'} |"
            )
        flags = convention_flags(results)
        lines += [
            "",
            "Convention flags: "
            + ("; ".join(f"{label} `{shape}`" for label, shape in flags) if flags else "none")
            + ".",
            "",
        ]
    (RESULTS / "COMPARISON.md").write_text("\n".join(lines), encoding="utf-8")
    print(RESULTS / "COMPARISON.md")


if __name__ == "__main__":
    main()
